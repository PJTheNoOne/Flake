#!/usr/bin/env bash

set -euo pipefail

CONFIG_HOME="${XDG_CONFIG_HOME:-"$HOME/.config"}"
STATE_HOME="${XDG_STATE_HOME:-"$HOME/.local/state"}"

PALETTE_FILE="$CONFIG_HOME/theme-switcher/palettes.json"

theme="${1:-tokyo-night}"

if [[ "$theme" == "list" ]]; then
  jq -r '.themes | to_entries[] | "\(.key) - \(.value.name)"' \
    "$PALETTE_FILE"
  exit 0
fi

if [[ "$#" -gt 1 ]]; then
  echo "Usage: theme-switch [theme-name|list]"
  exit 1
fi

if ! jq -e --arg theme "$theme" \
  '.themes | has($theme)' "$PALETTE_FILE" >/dev/null; then
  echo "Unknown theme: $theme"
  echo
  echo "Available themes:"
  jq -r '.themes | keys[]' "$PALETTE_FILE"
  exit 1
fi

get_color() {
  jq -er --arg theme "$theme" --arg key "$1" \
    '.themes[$theme][$key]' "$PALETTE_FILE"
}

write_atomic() {
  local destination="$1"
  local directory
  local temporary

  directory="$(dirname "$destination")"
  mkdir -p "$directory"

  temporary="$(mktemp "$directory/.${destination##*/}.XXXXXX")"

  cat > "$temporary"
  mv -f "$temporary" "$destination"
}

name="$(get_color name)"
mode="$(get_color mode)"

bg="$(get_color bg)"
bg1="$(get_color bg1)"
bg2="$(get_color bg2)"
fg="$(get_color fg)"
muted="$(get_color muted)"

red="$(get_color red)"
orange="$(get_color orange)"
yellow="$(get_color yellow)"
green="$(get_color green)"
cyan="$(get_color cyan)"
blue="$(get_color blue)"
purple="$(get_color purple)"
accent="$(get_color accent)"

mapfile -t ansi < <(
  jq -er --arg theme "$theme" \
    '.themes[$theme].ansi[]' "$PALETTE_FILE"
)

# ----------------------------------------------------------------------
# Waybar
# ----------------------------------------------------------------------

{
  printf '@define-color bg_dim %s;\n' "$bg"
  printf '@define-color bg0 %s;\n' "$bg"
  printf '@define-color bg1 %s;\n' "$bg1"
  printf '@define-color bg3 %s;\n' "$bg2"

  printf '@define-color bg_diff_red %s;\n' "$bg1"
  printf '@define-color bg_visual_red %s;\n' "$bg2"
  printf '@define-color bg_diff_blue %s;\n' "$bg2"

  printf '@define-color fg0 %s;\n' "$fg"
  printf '@define-color red %s;\n' "$red"
  printf '@define-color orange %s;\n' "$orange"
  printf '@define-color green %s;\n' "$green"
  printf '@define-color blue %s;\n' "$blue"
  printf '@define-color gray2 %s;\n' "$muted"

  printf '@define-color fujiWhite %s;\n' "$fg"
  printf '@define-color sumiInk1 %s;\n' "$bg"
  printf '@define-color boatYellow2 %s;\n' "$yellow"
  printf '@define-color surimiOrange %s;\n' "$orange"
} | write_atomic "$CONFIG_HOME/waybar/theme.css"

# Waybar SIGUSR2 reloads the bar with its updated configuration/style.
if pgrep -x waybar >/dev/null 2>&1; then
  pkill -USR2 -x waybar || true
fi

# ----------------------------------------------------------------------
# Ghostty
# ----------------------------------------------------------------------

{
  printf '# Generated by theme-switch. Do not edit manually.\n'
  printf 'background = %s\n' "$bg"
  printf 'foreground = %s\n' "$fg"
  printf 'cursor-color = %s\n' "$accent"
  printf 'cursor-text = %s\n' "$bg"
  printf 'selection-background = %s\n' "$bg2"
  printf 'selection-foreground = %s\n' "$fg"

  for i in "${!ansi[@]}"; do
    printf 'palette = %s=%s\n' "$i" "${ansi[$i]}"
  done
} | write_atomic "$CONFIG_HOME/ghostty/theme-switcher.conf"

# ----------------------------------------------------------------------
# Qt 5 / Qt 6
# ----------------------------------------------------------------------

# QPalette roles in Qt order:
# WindowText, Button, Light, Midlight, Dark, Mid, Text, BrightText,
# ButtonText, Base, Window, Shadow, Highlight, HighlightedText,
# Link, LinkVisited, AlternateBase, NoRole, ToolTipBase, ToolTipText,
# PlaceholderText.

qt_active=(
  "$fg" "$bg2" "$fg" "$bg2" "$bg2" "$bg2" "$fg"
  "$red" "$fg" "$bg" "$bg" "$muted" "$accent" "$bg"
  "$cyan" "$purple" "$bg1" "$fg" "$bg1" "$fg" "$muted"
)

qt_inactive=(
  "$fg" "$bg2" "$fg" "$bg2" "$bg2" "$bg2" "$fg"
  "$red" "$fg" "$bg" "$bg" "$muted" "$accent" "$bg"
  "$cyan" "$purple" "$bg1" "$fg" "$bg1" "$fg" "$muted"
)

qt_disabled=(
  "$muted" "$bg1" "$bg2" "$bg1" "$bg1" "$bg2" "$muted"
  "$red" "$muted" "$bg1" "$bg1" "$bg2" "$bg2" "$muted"
  "$muted" "$muted" "$bg1" "$muted" "$bg1" "$muted" "$muted"
)

join_colors() {
  local IFS=,
  printf '%s' "$*"
}

{
  printf '[ColorScheme]\n'
  printf 'active_colors=%s\n' "$(join_colors "${qt_active[@]}")"
  printf 'inactive_colors=%s\n' "$(join_colors "${qt_inactive[@]}")"
  printf 'disabled_colors=%s\n' "$(join_colors "${qt_disabled[@]}")"
} | write_atomic "$CONFIG_HOME/theme-switcher/qt-colors.conf"

# qt6ct watches its configuration directory for changes. Creating/removing
# a marker causes it to reload the settings and read the new palette.
for qtct_dir in "$CONFIG_HOME/qt5ct" "$CONFIG_HOME/qt6ct"; do
  if [[ -d "$qtct_dir" ]]; then
    marker="$(mktemp "$qtct_dir/.theme-switch.XXXXXX")"
    rm -f "$marker"
  fi
done

# ----------------------------------------------------------------------
# GTK
# ----------------------------------------------------------------------

# GTK/libadwaita receives a light/dark preference, not the full custom
# palette. The portal's standardized color-scheme setting is light/dark.
if command -v gsettings >/dev/null 2>&1 &&
   gsettings list-schemas | grep -Fxq 'org.gnome.desktop.interface'; then

  if gsettings list-keys org.gnome.desktop.interface |
     grep -Fxq 'color-scheme'; then

    if [[ "$mode" == "light" ]]; then
      gsettings set org.gnome.desktop.interface color-scheme 'prefer-light' \
        >/dev/null 2>&1 || true
    else
      gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark' \
        >/dev/null 2>&1 || true
    fi
  fi
fi

# ----------------------------------------------------------------------
# State
# ----------------------------------------------------------------------

printf '%s\n' "$theme" |
  write_atomic "$STATE_HOME/theme-switcher/current"

printf 'Theme switched to: %s (%s)\n' "$name" "$theme"


# ----------------------------------------------------------------------
# Fuzzel
# ----------------------------------------------------------------------

{
  printf '[colors]\n'
  printf 'background=%s\n' "${bg#\#}ff"
  printf 'text=%s\n' "${fg#\#}ff"
  printf 'prompt=%s\n' "${accent#\#}ff"
  printf 'placeholder=%s\n' "${muted#\#}ff"
  printf 'input=%s\n' "${fg#\#}ff"
  printf 'match=%s\n' "${cyan#\#}ff"
  printf 'selection=%s\n' "${bg2#\#}ff"
  printf 'selection-text=%s\n' "${fg#\#}ff"
  printf 'selection-match=%s\n' "${accent#\#}ff"
  printf 'border=%s\n' "${accent#\#}ff"

  printf '\n[border]\n'
  printf 'width=2\n'
  printf 'radius=10\n'
  printf 'selection-radius=6\n'
} | write_atomic "$CONFIG_HOME/fuzzel/theme-switcher.ini"
